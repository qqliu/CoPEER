#!/usr/bin/env python3
"""Render census tables/macros and descriptive figures from checked JSON outputs."""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path

BASE = Path(__file__).resolve().parent
ROOT = BASE.parents[2]
GENERATED = ROOT / 'paper_v2/generated'
FIGURES = ROOT / 'paper_v2/figures'
LABELS = {
    'family_documented': 'Infinite witness family',
    'repair_documented': 'Justified claim repair',
    'nondegenerate_alternative_documented': 'Named-restriction alternative',
    'exhaustive_domain_documented': 'Bounded exhaustive domain',
}
CORPORA = {
    'QEDBench (LLM-written proofs; certified + blind re-derived)': 'QEDBench, original',
    'QEDBench, second-model flags (confirmed)': 'QEDBench, second model',
    'Stack Exchange, question arm (confirmed)': 'Stack Exchange questions',
    'Stack Exchange, vetted-answer arm (certified)': 'Stack Exchange vetted answers',
    'math.StackExchange mined pool (confirmed)': 'math.SE mined',
    'math.StackExchange curated corpus (confirmed)': 'math.SE curated',
    'ProofWiki flagged proofs (newly confirmed)': 'ProofWiki, original',
    'ProofWiki flagged proofs (newly confirmed; Lean certified)': 'ProofWiki, certificate expansion',
    'Reddit proof-check posts (newly confirmed)': 'Reddit',
    'arXiv source-enriched proofs (newly confirmed)': 'arXiv',
    'Quarantined refutations (counterexample already published)': 'Previously published refutations',
}


def read(path):
    return json.loads(path.read_text())


def tex(text):
    return ''.join({'_': r'\_', '&': r'\&', '%': r'\%', '#': r'\#', '$': r'\$'}.get(c, c)
                   for c in str(text))


def write(name, value):
    (GENERATED / name).write_text('% Generated by analysis/counterexample_structure_20260910/render_paper.py\n' + value + '\n')


def validate_inputs(census, rows, audit, root=ROOT):
    """Reject stale or mismatched generated inputs before writing paper assets."""
    def require(condition, message):
        if not condition:raise ValueError(message)
    for path, expected in census['provenance'].items():
        require(hashlib.sha256((root / path).read_bytes()).hexdigest()==expected,
                'Stale census provenance; regenerate analysis: '+path)
    audit_provenance=audit['provenance']
    require(hashlib.sha256((root/audit_provenance['script_path']).read_bytes()).hexdigest()
            ==audit_provenance['script_sha256'], 'Stale audit analysis script provenance')
    c=census['counts']
    require(c['n']==len(rows) and len({r['record'] for r in rows})==len(rows),
            'Census row count or uniqueness differs')
    for key,entry in c['flags'].items():
        actual=sum(r[key] for r in rows)
        require(entry=={'yes':actual,'denominator':len(rows),'fraction':actual/len(rows)},
                'Census flag totals differ from rows: '+key)
    for key,expected in c['categorical'].items():
        require(dict(Counter(r[key] for r in rows))==expected,
                'Census categories differ from rows: '+key)
    require(c['family_and_repair']==sum(r['family_documented'] and r['repair_documented'] for r in rows),
            'Census family/repair intersection differs')
    require(c['family_or_repair']==sum(r['family_documented'] or r['repair_documented'] for r in rows),
            'Census family/repair union differs')
    require(set(c['by_corpus'])=={r['corpus'] for r in rows}, 'Census corpus identities differ')
    for corpus,expected in c['by_corpus'].items():
        subset=[r for r in rows if r['corpus']==corpus]
        require(expected=={'n':len(subset),**{key:sum(r[key] for r in subset) for key in c['flags']}},
                'Census corpus totals differ: '+corpus)
    canonical=[r['record'].replace('Graph Theory','Graph_Theory') for r in rows]
    released={r['record_id'] for r in audit['record_lineage'] if r['released']}
    require(len(set(canonical))==len(canonical) and set(canonical)==released,
            'Census and audit release identities differ')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--no-figures', action='store_true')
    args = parser.parse_args()
    census = read(BASE / 'results/census.json')
    rows = read(BASE / 'results/annotated_records.json')
    audit = read(BASE / 'results/audit_analysis.json')
    validate_inputs(census,rows,audit)
    c = census['counts']
    n = c['n']
    flag = lambda k: c['flags'][k]['yes']
    macros = {'cexN': n, 'cexFamily': flag('family_documented'),
              'cexRepair': flag('repair_documented'),
              'cexNondegenerate': flag('nondegenerate_alternative_documented'),
              'cexExhaustive': flag('exhaustive_domain_documented'),
              'cexFamilyRepairBoth': c['family_and_repair'],
              'cexFamilyRepairEither': c['family_or_repair'],
              'cexIntermediate': c['categorical']['refutation_role'].get('intermediate_step', 0),
              'cexTarget': c['categorical']['refutation_role'].get('target_statement', 0),
              'cexRoleUnknown': c['categorical']['refutation_role'].get('unclear', 0),
              'cexMinimalBounded': c['categorical']['minimality_scope'].get('search_order_or_bounded', 0),
              'cexMinimalGlobal': c['categorical']['minimality_scope'].get('global_argument', 0),
              'cexReviewN': census['review']['sample_n'],
              'cexCorrectedRecords': census['review']['corrected_records'],
              'cexAnyUncertainty': c['any_uncertainty']}
    for key, short in [('family_documented','Family'), ('repair_documented','Repair'),
                       ('nondegenerate_alternative_documented','Nondegenerate'),
                       ('exhaustive_domain_documented','Exhaustive')]:
        macros['cex'+short+'Pct'] = f'{100*flag(key)/n:.1f}'
        macros['cex'+short+'Strict'] = sum(r[key] and key not in r['uncertain_fields'] for r in rows)
        if key in c['documentation_length_by_flag']['flags']:
            lengths = c['documentation_length_by_flag']['flags'][key]
            for group, suffix in [('documented', 'DocMedian'), ('not_documented', 'NoDocMedian')]:
                macros['cex'+short+suffix] = f"{lengths[group]['median']:,.1f}".rstrip('0').rstrip('.')
    write('counterexample_structure_counts.tex', '\n'.join(
        '\\newcommand{\\' + k + '}{' + str(v) + '}' for k,v in macros.items()))
    table = [r'\begin{tabular}{lrr}', r'\toprule', r'Documented property & Records & Percent \\', r'\midrule']
    for key, label in LABELS.items():
        table.append(f'{label} & {flag(key)} & {100*flag(key)/n:.1f}\\% '+r'\\')
    table += [r'\midrule', f"Both family and repair & {c['family_and_repair']} & {100*c['family_and_repair']/n:.1f}\\% "+r'\\',
              r'\bottomrule', r'\end{tabular}']
    write('counterexample_structure_properties.tex','\n'.join(table))
    table = [r'\begin{tabular}{lrrrrr}',r'\toprule',r'Corpus stratum & $N$ & Family & Repair & Restriction & Exhaustive \\',r'\midrule']
    for name in CORPORA:
        d=c['by_corpus'][name]
        table.append(CORPORA[name]+' & '+' & '.join(str(d[k]) for k in ['n']+list(LABELS))+r' \\')
    table += [r'\midrule', 'Total & '+str(n)+' & '+' & '.join(str(flag(k)) for k in LABELS)+r' \\',r'\bottomrule',r'\end{tabular}']
    write('counterexample_structure_by_corpus.tex','\n'.join(table))
    table=[r'\begin{tabular}{lrrr}',r'\toprule',r'Field & Agree / $N$ & Agreement & $\kappa$ \\',r'\midrule']
    for key,d in census['review']['agreement_before_corrections'].items():
        label=LABELS.get(key,key.replace('_',' ').capitalize())
        kap='--' if d['cohen_kappa'] is None else f"{d['cohen_kappa']:.3f}"
        table.append(f"{label} & {d['agreements']}/{d['n']} & {100*d['agreement']:.1f}\\% & {kap} "+r'\\')
    table += [r'\bottomrule',r'\end{tabular}']
    write('counterexample_structure_agreement.tex','\n'.join(table))
    table=[r'\begin{tabular}{llr}',r'\toprule',r'Axis & Category & Records \\',r'\midrule']
    for key in ['object_kind','mechanism','refutation_role','minimality_scope']:
        for label,num in sorted(c['categorical'][key].items(),key=lambda kv:(-kv[1],kv[0])):
            table.append(f"{key.replace('_',' ')} & {label.replace('_',' ')} & {num} "+r'\\')
        table.append(r'\midrule')
    table[-1]=r'\bottomrule'
    table.append(r'\end{tabular}')
    write('counterexample_structure_categories.tex','\n'.join(table))
    strata=audit['later_holdout_by_reference_gate']['within_source_family']['strata']
    table=[r'\begin{tabular}{lrr}',r'\toprule',r'Source family & Prior adjudication & Prior corroboration \\',r'\midrule']
    for name,d in strata.items():
        vals=[d['by_reference_status'][s]['replication_held_out'] for s in ['PASS_ADJUDICATED','PASS_CORROBORATED']]
        table.append(name.replace('StackExchange','Stack Exchange')+' & '+' & '.join(
            (f"{v['numerator']}/{v['denominator']} ({100*v['proportion']:.1f}\\%)"
             if v['proportion'] is not None else '-- (no records)') for v in vals)+r' \\')
    table += [r'\bottomrule',r'\end{tabular}']
    write('counterexample_structure_audit_strata.tex','\n'.join(table))
    if not args.no_figures:
        import matplotlib
        matplotlib.use('Agg')
        import matplotlib.pyplot as plt
        plt.rcParams.update({'font.size':9,'font.family':'DejaVu Sans','pdf.fonttype':42,'ps.fonttype':42})
        fig, axes=plt.subplots(1,2,figsize=(7.0,2.65),gridspec_kw={'width_ratios':[1.1,1]})
        keys=list(LABELS)
        labels=['Infinite family','Claim repair','Named restriction','Exhaustive domain']
        for i,(key,label) in enumerate(zip(keys,labels)):
            value=100*flag(key)/n
            axes[0].barh(i,value,color='#246b87',height=.58)
            axes[0].text(value+.8,i,f'{flag(key)}/{n}',va='center',fontsize=8)
        axes[0].set_yticks(range(4),labels)
        axes[0].invert_yaxis()
        axes[0].set_xlim(0,46)
        axes[0].set_xlabel('Records with documented property (%)')
        axes[0].set_title('(a) Complete released-record census',loc='left',fontsize=9)
        names=['QEDBench','ProofWiki','Reddit','StackExchange','arXiv']
        for i,name in enumerate(names):
            vals=[strata[name]['by_reference_status'][s]['replication_held_out'] for s in ['PASS_CORROBORATED','PASS_ADJUDICATED']]
            xs=[100*v['proportion'] for v in vals]
            axes[1].plot(xs,[i,i],color='#c8cdd2',linewidth=1.3,zorder=1)
            for x,v,color,marker in zip(xs,vals,['#246b87','#c95d39'],['o','s']):
                axes[1].scatter(x,i,color=color,marker=marker,s=27,zorder=2)
                axes[1].annotate(f"{v['numerator']}/{v['denominator']}",(x,i),xytext=(3,5),textcoords='offset points',fontsize=7)
        axes[1].set_yticks(range(5),[x.replace('StackExchange','Stack Exch.') for x in names])
        axes[1].invert_yaxis()
        axes[1].set_xlim(-2,55)
        axes[1].set_ylim(4.5,-.7)
        axes[1].set_xlabel('Held out in later replication (%)')
        axes[1].set_title('(b) Same pattern within source families',loc='left',fontsize=9)
        axes[1].scatter([],[],color='#246b87',s=20,label='Prior corroboration')
        axes[1].scatter([],[],color='#c95d39',marker='s',s=20,label='Prior adjudication')
        axes[1].legend(loc='lower center',bbox_to_anchor=(.48,-.47),frameon=False,ncol=2,fontsize=7)
        for ax in axes:
            ax.spines[['top','right']].set_visible(False)
            ax.grid(axis='x',alpha=.18)
            ax.set_axisbelow(True)
        fig.tight_layout(w_pad=2)
        for ext in ['pdf','png']:
            fig.savefig(FIGURES/f'counterexample_structure_census.{ext}',bbox_inches='tight',dpi=180)
        plt.close(fig)
    print(json.dumps({'records':n,'macros':len(macros),'generated_tables':6,'figures':not args.no_figures}))


if __name__=='__main__':
    main()
