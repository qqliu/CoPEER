"""The proof claims that H_1 ∩ N_2 is normal in H_1, although the hypotheses only establish that N_2 is normal in H_2."""

import itertools
import json


POINTS = (0, 1, 2)
ELEMENTS = tuple(itertools.permutations(POINTS))
IDENTITY = POINTS


def compose(left, right):
    return tuple(left[right[index]] for index in POINTS)


def inverse(permutation):
    result = [0, 0, 0]
    for source, target in enumerate(permutation):
        result[target] = source
    return tuple(result)


def is_subgroup(candidate):
    if IDENTITY not in candidate:
        return False
    for element in candidate:
        if inverse(element) not in candidate:
            return False
        for other in candidate:
            if compose(element, other) not in candidate:
                return False
    return True


def is_normal(candidate, group):
    if not candidate.issubset(group):
        return False
    for conjugator in group:
        conjugator_inverse = inverse(conjugator)
        for element in candidate:
            conjugate = compose(compose(conjugator, element), conjugator_inverse)
            if conjugate not in candidate:
                return False
    return True


def subset_from_mask(mask):
    return frozenset(
        element
        for index, element in enumerate(ELEMENTS)
        if mask & (1 << index)
    )


def main():
    subgroups = tuple(
        candidate
        for mask in range(1 << len(ELEMENTS))
        for candidate in (subset_from_mask(mask),)
        if is_subgroup(candidate)
    )
    assert len(subgroups) == 6

    witnesses = []
    triples_checked = 0
    for h1 in subgroups:
        for h2 in subgroups:
            for n2 in subgroups:
                triples_checked += 1
                if is_normal(n2, h2):
                    intersection = h1.intersection(n2)
                    if not is_normal(intersection, h1):
                        witnesses.append((h1, h2, n2))

    assert triples_checked == 216
    transposition_12 = (0, 2, 1)
    expected_n2 = frozenset((IDENTITY, transposition_12))
    expected = (frozenset(ELEMENTS), expected_n2, expected_n2)
    assert witnesses
    assert witnesses[0] == expected

    result = {
        "record_id": "proofwiki_13715__codex_expansion",
        "outcome": "WITNESS_FOUND",
        "witness_description": "Within S_3 on {0,1,2}, take H_1=S_3 and H_2=N_2={identity,(1 2)}.",
        "refutation_explanation": "Here N_2=H_2, so N_2 is normal in H_2. However, H_1 intersection N_2=N_2, and conjugation by (0 1) sends (1 2) to (0 2), which is not in N_2. Thus H_1 intersection N_2 is not normal in H_1.",
        "search_space": "All 216 ordered triples (H_1,H_2,N_2) of subgroups of S_3 (the six subgroups are generated by exhaustive inspection of all 64 subsets), filtering for N_2 normal in H_2 and checking H_1 intersection N_2 for normality in H_1."
    }
    print(json.dumps(result, separators=(",", ":")))


if __name__ == "__main__":
    main()
