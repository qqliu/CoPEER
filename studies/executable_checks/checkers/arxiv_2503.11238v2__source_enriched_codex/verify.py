r"""A cyclic subgroup of order m in the group generated by the input graph’s edge transpositions implies that the input graph contains a cycle of length m."""

import json

RECORD_ID = "arxiv_2503.11238v2__source_enriched_codex"
CONFIRMED_NOTES = (
    "Exact independent recomputation confirms that the two edge transpositions "
    "generate an element of order 3, hence a cyclic subgroup of order 3, while "
    "the two-edge graph has no 3-cycle. The refuted statement is substantive, "
    "not plainly a typo."
)


def compose(first, second):
    return tuple(first[second[position]] for position in range(3))


def main():
    identity = (0, 1, 2)
    swap_zero_one = (1, 0, 2)
    swap_zero_two = (2, 1, 0)

    generated_element = compose(swap_zero_one, swap_zero_two)
    square = compose(generated_element, generated_element)
    cube = compose(generated_element, square)
    subgroup = {identity, generated_element, square}

    has_order_three = (
        generated_element != identity
        and square != identity
        and cube == identity
    )
    is_subgroup = (
        len(subgroup) == 3
        and all(compose(left, right) in subgroup
                for left in subgroup for right in subgroup)
        and all(any(compose(element, candidate) == identity
                    and compose(candidate, element) == identity
                    for candidate in subgroup)
                for element in subgroup)
    )

    vertices = (0, 1, 2)
    edges = {frozenset((0, 1)), frozenset((0, 2))}
    graph_has_triangle = False
    for first in vertices:
        for second in vertices:
            for third in vertices:
                if len({first, second, third}) != 3:
                    continue
                required = {
                    frozenset((first, second)),
                    frozenset((second, third)),
                    frozenset((third, first)),
                }
                if required.issubset(edges):
                    graph_has_triangle = True

    verified = has_order_three and is_subgroup and not graph_has_triangle
    verdict = "CONFIRMED" if verified else "REFUTED_WITNESS_INVALID"
    notes = CONFIRMED_NOTES if verified else (
        "Independent exact recomputation did not validate the reported witness."
    )
    print(json.dumps({
        "record_id": RECORD_ID,
        "verdict": verdict,
        "notes": notes,
    }, separators=(",", ":")))


if __name__ == "__main__":
    main()
