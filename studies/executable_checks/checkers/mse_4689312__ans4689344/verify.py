r'''Notably, every subgroup of $S_7$ generated by two $7$-cycles is either a cyclic group of order $7$, the group $PSL(2,7)$ we want, or all of $S_7$.'''

import json

record_id = "mse_4689312__ans4689344"
confirmed_notes = "Confirmed by exact enumeration: both maps are 7-cycles and their generated subgroup has 2520 elements, so its order is neither 7, 168, nor 5040. It is A_7. The refuted wording is plainly a typo rather than a substantive counterexample to the intended classification: \"S_7\" should be \"A_7\", since every 7-cycle is even."
invalid_notes = "The reported witness could not be independently validated."

n = 7
points = tuple(range(n))
a = (1, 2, 3, 4, 5, 6, 0)
b = (1, 2, 3, 4, 6, 0, 5)


def is_seven_cycle(permutation):
    if tuple(sorted(permutation)) != points:
        return False
    visited = set()
    position = 0
    for unused_index in points:
        if position in visited:
            return False
        visited.add(position)
        position = permutation[position]
    return position == 0 and visited == set(points)


def inverse(permutation):
    answer = [0 for unused_index in points]
    for preimage in points:
        answer[permutation[preimage]] = preimage
    return tuple(answer)


def followed_by(first, second):
    return tuple(second[first[position]] for position in points)


def closure(generators):
    identity = points
    known = {identity}
    frontier = {identity}
    while frontier:
        next_frontier = set()
        for element in frontier:
            for generator in generators:
                candidate = followed_by(element, generator)
                if candidate not in known:
                    next_frontier.add(candidate)
        known.update(next_frontier)
        frontier = next_frontier
    return known


def is_even(permutation):
    inversions = 0
    for left in points:
        for right in range(left + 1, n):
            if permutation[left] > permutation[right]:
                inversions += 1
    return inversions % 2 == 0


def factorial(value):
    product = 1
    for factor in range(2, value + 1):
        product *= factor
    return product


def gcd(first, second):
    while second:
        first, second = second, first % second
    return first


generators = (a, b, inverse(a), inverse(b))
group = closure(generators)
symmetric_order = factorial(n)
q = 7
psl_order = q * (q * q - 1) // gcd(2, q - 1)
alternative_orders = (n, psl_order, symmetric_order)
valid = (
    is_seven_cycle(a)
    and is_seven_cycle(b)
    and len(group) == 2520
    and len(group) not in alternative_orders
    and all(is_even(element) for element in group)
    and len(group) * 2 == symmetric_order
)

result = {
    "record_id": record_id,
    "verdict": "CONFIRMED" if valid else "REFUTED_WITNESS_INVALID",
    "notes": confirmed_notes if valid else invalid_notes,
}
print(json.dumps(result))
