r"""If the full generating tuple is algebraically dependent, then the final generator is algebraic over the algebra generated by the preceding generators."""

import json
from fractions import Fraction

RECORD_ID = "proofwiki_8791__codex_expansion"
VERDICT = "CONFIRMED"
NOTES = (
    "Confirmed: exact canonical polynomial arithmetic verifies that the nonzero "
    "relation X1 vanishes at (0,t), while Q[0]=Q and substitution Z↦t "
    "identifies each polynomial in Q[Z] with the same coefficient vector in "
    "Q[t], so its kernel is zero. Thus t is not algebraic over Q. The refuted "
    "statement is substantive, not plainly a typo: dependence can arise solely "
    "from a preceding generator."
)


def canonical(coefficients):
    values = [Fraction(value) for value in coefficients]
    while values and values[-1] == 0:
        values.pop()
    return tuple(values)


def add(left, right):
    size = max(len(left), len(right))
    result = []
    for index in range(size):
        a = left[index] if index < len(left) else Fraction(0)
        b = right[index] if index < len(right) else Fraction(0)
        result.append(a + b)
    return canonical(result)


def multiply(left, right):
    if not left or not right:
        return ()
    result = [Fraction(0) for _ in range(len(left) + len(right) - 1)]
    for i, a in enumerate(left):
        for j, b in enumerate(right):
            result[i + j] += a * b
    return canonical(result)


def nonnegative_power(base, exponent):
    if not isinstance(exponent, int) or exponent < 0:
        raise ValueError("exponent must be a nonnegative integer")
    result = (Fraction(1),)
    factor = canonical(base)
    remaining = exponent
    while remaining:
        if remaining % 2:
            result = multiply(result, factor)
        remaining //= 2
        if remaining:
            factor = multiply(factor, factor)
    return result


def evaluate_bivariate(terms, first, second):
    total = ()
    for (first_degree, second_degree), coefficient in terms.items():
        monomial = multiply(
            nonnegative_power(first, first_degree),
            nonnegative_power(second, second_degree),
        )
        total = add(total, tuple(coefficient * item for item in monomial))
    return total


zero = ()
t = canonical((Fraction(0), Fraction(1)))
y1 = zero
y2 = t

# X1 is nonzero as a formal bivariate polynomial and vanishes at (0,t).
relation = {(1, 0): Fraction(1)}
relation_is_nonzero = any(coefficient != 0 for coefficient in relation.values())
relation_vanishes = evaluate_bivariate(relation, y1, y2) == zero

# For every f in Q[Z], f(0) is its constant coefficient, and every rational
# constant occurs from a constant f. Therefore the generated algebra Q[0] is Q.
preceding_algebra_is_q = y1 == zero

# Canonical polynomials are finite coefficient vectors. Substitution Z -> t
# sends sum(c_i Z^i) to sum(c_i t^i), which has exactly the same canonical
# vector. Hence the substitution map Q[Z] -> Q[t] is injective for every finite
# vector, and no nonzero polynomial can annihilate t.
def substitute_z_at_t(coefficients):
    polynomial = canonical(coefficients)
    total = ()
    for degree, coefficient in enumerate(polynomial):
        term = tuple(coefficient * item for item in nonnegative_power(t, degree))
        total = add(total, term)
    return total


basis_checks = all(
    substitute_z_at_t(tuple([Fraction(0)] * degree + [Fraction(1)]))
    == nonnegative_power(t, degree)
    for degree in range(9)
)
coefficientwise_identity = (
    canonical((Fraction(2), Fraction(-3), Fraction(5)))
    == substitute_z_at_t((Fraction(2), Fraction(-3), Fraction(5)))
)
substitution_kernel_is_zero = basis_checks and coefficientwise_identity and y2 == t
final_generator_is_not_algebraic = substitution_kernel_is_zero

confirmed = (
    relation_is_nonzero
    and relation_vanishes
    and preceding_algebra_is_q
    and final_generator_is_not_algebraic
)
actual_verdict = "CONFIRMED" if confirmed else "REFUTED_WITNESS_INVALID"
actual_notes = NOTES if confirmed else "The proposed witness did not pass exact verification."

print(json.dumps({
    "record_id": RECORD_ID,
    "verdict": actual_verdict,
    "notes": actual_notes,
}, separators=(",", ":")))
