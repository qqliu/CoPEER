# P31: exact check of the supplied witness in G = S_3: P=<(12)>, H=<(13)>, g=(123), h=(23).
from itertools import permutations
def mul(p,q): return tuple(p[q[i]] for i in range(3))     # (p*q)(i) = p(q(i))
def inv(p):
    r=[0]*3
    for i,x in enumerate(p): r[x]=i
    return tuple(r)
e=(0,1,2)
def cyc(*c):
    p=list(range(3))
    for i in range(len(c)): p[c[i]-1]=c[(i+1)%len(c)]-1
    return tuple(p)
def gen(gs):
    S={e}
    while True:
        n={mul(a,b) for a in S for b in gs}|S
        if n==S: return S
        S=n
def coset(x,P): return frozenset(mul(x,p) for p in P)
name={e:"e",cyc(1,2):"(12)",cyc(1,3):"(13)",cyc(2,3):"(23)",cyc(1,2,3):"(123)",cyc(1,3,2):"(132)"}
P=gen({cyc(1,2)}); H=gen({cyc(1,3)}); g=cyc(1,2,3); h=cyc(2,3)
print("P =",sorted(name[x] for x in P)," H = <(13)> =",sorted(name[x] for x in H))
print("g =",name[g]," h =",name[h]," h in H ?", h in H, "   <-- the witness's h is NOT in the H it names")
print("hgP =",sorted(name[x] for x in coset(mul(h,g),P)))
print("gP  =",sorted(name[x] for x in coset(g,P)))
print("hgP == gP :", coset(mul(h,g),P)==coset(g,P))
ghg=mul(mul(g,h),inv(g)); gih=mul(mul(inv(g),h),g)
print("ghg^-1 =",name[ghg]," in P ?", ghg in P, "   (line 27's claimed consequence)")
print("g^-1hg =",name[gih]," in P ?", gih in P, "   (the correct consequence of hgP=gP)")
print("so at the supplied (P,g,h): hgP=gP holds and ghg^-1 not in P ->", coset(mul(h,g),P)==coset(g,P) and ghg not in P)
# is the supplied triple an instance of the source's setting? test both readings of H
for lbl,HH in (("<(13)> (as named)",H),("<(23)> (the group generated by the h actually used)",gen({h}))):
    fixed=all(coset(mul(x,g),P)==coset(g,P) for x in HH)
